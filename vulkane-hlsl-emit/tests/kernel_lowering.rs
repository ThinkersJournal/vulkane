//! ROADMAP rows 8a, 8b and 8g for HLSL: `Hlsl::lower_kernel` is `fishstringer-slang-emit`'s kernel
//! lowering (Slang's dialect is HLSL) with the header relabelled. The block-reverse kernel of
//! `vulkane-spirv-emit`'s tests is lowered, compiled by `dxc`, validated by `spirv-val` and run on
//! a device: right only because `GroupMemoryBarrierWithGroupSync()` separates the shared-memory
//! writes from the reads.
//!
//! **What differs from the SPIR-V emitter, on purpose:** a buffer is a strided *view* here (base and
//! strides in a `ConstantBuffer` after the buffers, `int64_t`, so the device needs `shaderInt64`),
//! and the coverage is the Slang emitter's (no bitwise `BinaryOp` in a kernel expression yet, so
//! the SPIR-V flow kernel is not lowered).
//!
//! Without a device, `dxc` or `spirv-val` the tests follow `VULKANE_REQUIRE_DEVICE`,
//! `VULKANE_REQUIRE_DXC` and `VULKANE_REQUIRE_SPIRV_VAL` rather than passing silently.

