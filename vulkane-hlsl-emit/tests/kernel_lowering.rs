fn lower(with_barrier: bool) -> GeneratedKernel {
    Hlsl.lower_kernel(&reverse_kernel::reverse(
        WORKGROUP_SIZE,
        with_barrier,
        false,
    ))
    .expect("the HLSL backend lowers the reverse kernel")
}

/// `dxc` to SPIR-V words; `None` when `dxc` is absent (a failure under `VULKANE_REQUIRE_DXC`).
fn dxc_words(k: &GeneratedKernel) -> Option<Vec<u32>> {
    let dir = tempfile::tempdir().unwrap();
    let (src, spv) = (dir.path().join("k.hlsl"), dir.path().join("k.spv"));
    std::fs::write(&src, &k.source).unwrap();
    let out = Command::new("dxc")
        .args([
            "-T",
            "cs_6_2",
            "-E",
            &k.name,
            "-spirv",
            "-fspv-target-env=vulkan1.1",
        ])
        .arg(&src)
        .arg("-Fo")
        .arg(&spv)
        .output();
    let out = match out {
        Ok(o) => o,
        Err(e) => {
            assert!(
                std::env::var_os("VULKANE_REQUIRE_DXC").is_none(),
                "VULKANE_REQUIRE_DXC is set but `dxc` could not be run: {e}"
            );
            return None;
        }
    };
    assert!(
        out.status.success(),
        "dxc failed:\n{}\n--- source ---\n{}",
        String::from_utf8_lossy(&out.stderr),
        k.source
    );
    let bytes = std::fs::read(&spv).unwrap();
    Some(
        bytes
            .chunks_exact(4)
            .map(|w| u32::from_le_bytes(w.try_into().unwrap()))
            .collect(),
    )
}

/// `spirv-val --target-env vulkan1.1` over `words`; `None` when it is absent and not required.
fn validates(words: &[u32]) -> Option<(bool, String)> {
    let bytes: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
    let child = Command::new("spirv-val")
        .args(["--target-env", "vulkan1.1", "-"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .and_then(|mut c| {
            let _ = c.stdin.take().expect("piped stdin").write_all(&bytes);
            c.wait_with_output()
        });
    match child {
        Ok(o) => Some((
            o.status.success(),
            String::from_utf8_lossy(&o.stderr).into_owned(),
        )),
        Err(e) => {
            assert!(
                std::env::var_os("VULKANE_REQUIRE_SPIRV_VAL").is_none(),
                "VULKANE_REQUIRE_SPIRV_VAL is set but `spirv-val` could not be run: {e}"
            );
            None
        }
    }
}

#[test]
fn the_reverse_kernel_has_the_group_barrier_and_its_control_does_not() {
    let (with, without) = (lower(true), lower(false));
    let barrier = "GroupMemoryBarrierWithGroupSync();";
    assert_eq!(with.source.matches(barrier).count(), 1, "{}", with.source);
    assert_eq!(
        without.source.matches(barrier).count(),
        0,
        "{}",
        without.source
    );
    assert!(
        with.source.contains("groupshared uint a0[256]"),
        "{}",
        with.source
    );
    assert!(
        with.source
            .starts_with("// Generated by vulkane-hlsl-emit (lower_kernel"),
        "{}",
        with.source
    );
    assert!(
        !with
            .source
            .contains("fishstringer-slang-emit (lower_kernel)")
    );
}

#[test]
fn dxc_compiles_the_lowered_kernel_and_spirv_val_accepts_it() {
    let Some(words) = dxc_words(&lower(true)) else {
        return;
    };
    if let Some((ok, err)) = validates(&words) {
        assert!(ok, "spirv-val rejected the dxc output:\n{err}");
    }
}

/// The params block: strides 1 and base 0 for each buffer view, packed by the interface's offsets.
fn params_bytes(k: &GeneratedKernel) -> Vec<u8> {
    let block = k
        .interface()
        .as_ref()
        .and_then(|i| i.params_block.as_ref())
        .expect("a kernel with buffer views carries a params block");
    let mut bytes = vec![0u8; usize::try_from(block.size).unwrap()];
    for f in &block.fields {
        assert_eq!(f.ty, ElementKind::I64, "{}", f.name);
        let v: i64 = if f.name.ends_with("_base") { 0 } else { 1 };
        let at = usize::try_from(f.offset).unwrap();
        bytes[at..at + 8].copy_from_slice(&v.to_le_bytes());
    }
    bytes
}

fn run(gpu: &gpu::Gpu, with_barrier: bool, input: &[u32]) -> Option<Vec<u32>> {
    let k = lower(with_barrier);
    let words = dxc_words(&k)?;
    Some(gpu.run_params(&k.name, &words, &[input], &params_bytes(&k)))
}

#[test]
fn a_block_reversed_through_groupshared_memory_is_exact_with_the_barrier() {
    common::require_serialization_lock();
    let features = DeviceFeatures::new().with_shader_int64();
    let Some(gpu) = gpu::Gpu::open_with("hlsl_kernel_barrier", Some((&features, "shaderInt64")))
    else {
        return; // skip already declared
    };
    let input: Vec<u32> = (0..WORKGROUP_SIZE).map(|i| i * 7 + 1).collect();
    let want: Vec<u32> = input.iter().rev().copied().collect();
    let Some(got) = run(&gpu, true, &input) else {
        return; // no dxc, declared above
    };
    assert_eq!(got, want, "the barriered kernel must reverse exactly");

    // Control, reported not asserted (a missing barrier is a race a device may not show).
    if let Some(racy) = run(&gpu, false, &input) {
        let wrong = racy.iter().zip(&want).filter(|(g, w)| g != w).count();
        eprintln!(
            "hlsl kernel_barrier control: without the barrier {wrong} of {} cells differ",
            want.len()
        );
    }
}

/// Row 8f: the shared 3-D kernel (non-cubic block and grid) through HLSL, every cell checked.
#[test]
fn a_non_cubic_3d_launch_writes_every_cell_its_own_ids_on_a_device() {
    common::require_serialization_lock();
    let features = DeviceFeatures::new().with_shader_int64();
    let Some(gpu) = gpu::Gpu::open_with("hlsl_kernel_grid", Some((&features, "shaderInt64")))
    else {
        return; // skip already declared
    };
    let k = Hlsl
        .lower_kernel(&grid_kernel::grid_kernel())
        .expect("the HLSL backend lowers the 3-D kernel");
    let Some(words) = dxc_words(&k) else {
        return; // no dxc, declared above
    };
    let cells = grid_kernel::cells();
    let got = gpu.run_grid_params(
        &k.name,
        &words,
        cells,
        grid_kernel::GRID,
        Some(&params_bytes(&k)),
    );
    let nx = (grid_kernel::BLOCK[0] * grid_kernel::GRID[0]) as usize;
    let ny = (grid_kernel::BLOCK[1] * grid_kernel::GRID[1]) as usize;
    for (i, &w) in got.iter().enumerate() {
        let (x, y, z) = (i % nx, (i / nx) % ny, i / (nx * ny));
        let want = grid_kernel::expected(x as u32, y as u32, z as u32);
        assert_eq!(
            w, want,
            "cell ({x},{y},{z})
{}",
            k.source
        );
    }
}

/// Row 8k: a per-thread `Private` array indexed by data, through HLSL; each thread reads its own value.
#[test]
fn a_private_array_with_data_dependent_indexing_is_per_thread_on_a_device() {
    common::require_serialization_lock();
    let features = DeviceFeatures::new().with_shader_int64();
    let Some(gpu) = gpu::Gpu::open_with("hlsl_kernel_private", Some((&features, "shaderInt64")))
    else {
        return; // skip already declared
    };
    let n = WORKGROUP_SIZE;
    let k = Hlsl
        .lower_kernel(&private_kernel::private_index(n, MemorySpace::Private))
        .expect("the HLSL backend lowers the private-array kernel");
    let Some(words) = dxc_words(&k) else {
        return; // no dxc, declared above
    };
    let input: Vec<u32> = (0..n).map(|t| (t * 5 + 1) % 4).collect();
    let want: Vec<u32> = (0..n).map(|t| t + 10 * input[t as usize]).collect();
    let got = gpu.run_params(&k.name, &words, &[&input], &params_bytes(&k));
    assert_eq!(got, want, "{}", k.source);
    // Control: the indices differ between threads, so a wrong-index lowering could not pass.
    assert!(input.iter().any(|&i| i != input[0]));
}

